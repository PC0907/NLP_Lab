#!/bin/bash
# ============================================================================
# install_smokefix.sh -- fixes the smoke-test runner.
#
# The previous version read the model from an environment variable, but the job
# runs with --export=NONE, so SLURM stripped it and the config's placeholder was
# used instead -- surfacing as a confusing 401 from the Hub. It now takes the
# model as a positional argument, which sbatch does pass through, and refuses to
# start if the name is still a placeholder.
#
# Also: 00_download_model.py now takes any model id instead of hardcoding one.
#
# Run from the repo root:   bash install_smokefix.sh    (then delete it)
# ============================================================================
set -euo pipefail
if [ ! -d scripts ] || [ ! -d src/probe_extraction ]; then
  echo "FATAL: run this from the NLP_Lab repo root."; exit 1
fi
TS=$(date +%Y%m%d-%H%M%S)
write_file() {
  local path="$1" want="$2" b64 got cur
  b64=$(cat)
  if [ -f "$path" ]; then
    cur=$(sha256sum "$path" | cut -d' ' -f1)
    if [ "$cur" = "$want" ]; then echo "  ok  $path (unchanged)"; return 0; fi
    cp -p "$path" "${path}.bak.${TS}"
  fi
  printf '%s' "$b64" | base64 -d > "$path"
  got=$(sha256sum "$path" | cut -d' ' -f1)
  if [ "$got" != "$want" ]; then
    echo "FATAL: checksum mismatch for $path"; exit 1
  fi
  echo "  ok  $path"
}
